package dev.fitnessapp.sim.seedgen

import dev.fitnessapp.algo.EngineVersion
import dev.fitnessapp.algo.core.det.Jcs
import dev.fitnessapp.algo.core.params.ParamsHashes
import dev.fitnessapp.algo.core.registry.ModuleRegistry
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.io.File

/**
 * Seed generator (DATA_MODEL.md 13.3): reads the repo JSON that the APK also bundles and emits the data
 * migration SQL, so the server seed and the bundled assets always agree. Reference rows use the
 * idempotent upsert pattern of 7.10; the immutable params and algorithm-version rows use
 * `on conflict do nothing` plus an assertion that the stored hash equals the generated one.
 */
object SeedGen {
    /** Column types needing a cast; everything else is text, boolean or a plain number. */
    private val TEXT_ARRAYS = setOf("aliases", "svg_region_ids", "ui_contexts", "joint_keys", "body_region_codes", "payload_keys")
    private val JSONB = setOf("default_load_scheme")

    private val REFERENCE_TABLES = listOf(
        "muscle_groups" to "id", "muscle_regions" to "id", "reason_codes" to "code", "metric_defs" to "code",
        "body_regions" to "code", "symptom_codes" to "code", "equipment_types" to "key",
        "session_event_types" to "event_type",
    )

    /** Largest params chunk (canonical JSON characters) per part, so each part fits one MCP call. */
    private const val CHUNK_CHARS = 30_000

    /**
     * Migration 005 as ordered parts `(name, sql)`. Part 1 seeds the reference tables; the params set is
     * too large for one apply call, so it is written as a `draft` row in chunks and activated (with key
     * count and hash assertions, plus the algorithm_versions rows) by the last part.
     */
    fun generate(resources: File, paramsVersion: String): List<Pair<String, String>> {
        val parts = mutableListOf<Pair<String, String>>()
        val ref = StringBuilder()
        ref.append(header("fitness_005_reference_seed_part1", "reference tables", paramsVersion))
        for ((table, pk) in REFERENCE_TABLES) {
            val file = File(resources, "reference/$table.json")
            val rows = Json.parseToJsonElement(file.readText(Charsets.UTF_8)).jsonObject.getValue("rows").jsonArray
            ref.append(upsert(table, pk, rows.map { it.jsonObject }))
            ref.appendLine()
        }
        parts += "fitness_005_reference_seed_part1" to ref.toString()
        params(resources, paramsVersion).forEachIndexed { i, sql ->
            val name = "fitness_005_reference_seed_part${i + 2}"
            parts += name to header(name, "algo_params $paramsVersion", paramsVersion) + sql
        }
        return parts
    }

    private fun header(name: String, what: String, paramsVersion: String): String = buildString {
        appendLine("-- $name (M0, data): $what — DATA_MODEL.md 9.1, 7.10, 13.2, 13.3")
        appendLine("--")
        appendLine("-- GENERATED by `gradlew :sim:run --args=\"seedgen\"` from algo/src/main/resources/fitness/")
        appendLine("-- (reference/*.json and params/default-params-$paramsVersion.json). Do not edit by hand.")
        appendLine("-- Idempotent: re-running changes nothing. Apply the parts in order.")
        appendLine()
    }

    private fun upsert(table: String, pk: String, rows: List<JsonObject>): String {
        val cols = rows.first().keys.toList()
        rows.forEach { require(it.keys.toList() == cols) { "$table: every row must have the same columns" } }
        val rest = cols.filter { it != pk }
        val sb = StringBuilder()
        sb.appendLine("-- fitness.$table (${rows.size} rows)")
        sb.appendLine("insert into fitness.$table (${cols.joinToString(", ")})")
        sb.appendLine("values")
        sb.appendLine(rows.joinToString(",\n") { r -> "  (" + cols.joinToString(", ") { c -> literal(c, r.getValue(c)) } + ")" })
        sb.appendLine("on conflict ($pk) do update")
        sb.appendLine("  set " + rest.joinToString(",\n      ") { "$it = excluded.$it" })
        sb.appendLine("  where (" + rest.joinToString(", ") { "fitness.$table.$it" } + ")")
        sb.appendLine("        is distinct from")
        sb.appendLine("        (" + rest.joinToString(", ") { "excluded.$it" } + ");")
        return sb.toString()
    }

    private fun params(resources: File, version: String): List<String> {
        val file = File(resources, "params/default-params-$version.json")
        val doc = Json.parseToJsonElement(file.readText(Charsets.UTF_8)).jsonObject
        require(doc.getValue("params_version").jsonPrimitive.content == version) { "params_version mismatch" }
        val params = doc.getValue("params").jsonObject
        val values = ParamsHashes.values(params)
        val hash = ParamsHashes.hash(values)
        val slices = ParamsHashes.slices(values)
        val range = doc.getValue("engine_version_range").jsonPrimitive.content
        val engine = EngineVersion.ENGINE_VERSION

        // Chunks of whole entries in code-point key order.
        val chunks = mutableListOf<JsonObject>()
        var current = LinkedHashMap<String, JsonElement>()
        var size = 0
        for (key in params.keys.sorted()) {
            val entry = params.getValue(key)
            val len = Jcs.canonicalize(entry).length + key.length + 4
            if (size + len > CHUNK_CHARS && current.isNotEmpty()) {
                chunks += JsonObject(current); current = LinkedHashMap(); size = 0
            }
            current[key] = entry; size += len
        }
        if (current.isNotEmpty()) chunks += JsonObject(current)

        val out = mutableListOf<String>()
        chunks.forEachIndexed { i, chunk ->
            val sb = StringBuilder()
            sb.appendLine("-- fitness.algo_params $version: chunk ${i + 1}/${chunks.size} (${chunk.size} of ${params.size} keys), written to a draft row.")
            if (i == 0) {
                sb.appendLine("insert into fitness.algo_params (params_version, status, engine_version_range, params, params_hash, notes)")
                sb.appendLine("values (${q(version)}, 'draft', ${q(range)}, ${q(Jcs.canonicalize(chunk))}::jsonb, ${q(hash)},")
                sb.appendLine("        'Bundled defaults; generated from ALGORITHMS.md Part C, ALGORITHMS_PLANNING.md section 23, CHALLENGE_ENGINE and UX.')")
                sb.appendLine("on conflict (params_version) do nothing;")
            } else {
                sb.appendLine("update fitness.algo_params")
                sb.appendLine("  set params = params || ${q(Jcs.canonicalize(chunk))}::jsonb")
                sb.appendLine("  where params_version = ${q(version)} and status = 'draft';")
            }
            out += sb.toString()
        }

        val sb = StringBuilder()
        sb.appendLine("-- Activate fitness.algo_params $version (${params.size} keys) and register ${ModuleRegistry.entries.size} module versions.")
        sb.appendLine("do $$")
        sb.appendLine("begin")
        sb.appendLine("  if exists (select 1 from fitness.algo_params where params_version = ${q(version)} and status = 'draft')")
        sb.appendLine("     and (select count(*) from fitness.algo_params a, jsonb_object_keys(a.params) where a.params_version = ${q(version)}) <> ${params.size} then")
        sb.appendLine("    raise exception 'algo_params $version: expected ${params.size} keys before activation';")
        sb.appendLine("  end if;")
        sb.appendLine("end;")
        sb.appendLine("$$;")
        sb.appendLine("update fitness.algo_params set status = 'active', released_at = now()")
        sb.appendLine("  where params_version = ${q(version)} and status = 'draft';")
        sb.appendLine()
        sb.appendLine("insert into fitness.algorithm_versions (module_id, version, layer, engine_version, status, default_params_version, constants_hash)")
        sb.appendLine("values")
        sb.appendLine(ModuleRegistry.entries.joinToString(",\n") { e ->
            val id = e.ref.id.value
            "  (${q(id)}, ${q(e.ref.version.toString())}, ${q(e.layer.name.lowercase())}, ${q(engine)}, 'active', ${q(version)}, ${q(ParamsHashes.hash(slices.getValue(id)))})"
        })
        sb.appendLine("on conflict (module_id, version) do nothing;")
        sb.appendLine()
        sb.appendLine("do $$")
        sb.appendLine("begin")
        sb.appendLine("  if (select params_hash from fitness.algo_params where params_version = ${q(version)}) <> ${q(hash)} then")
        sb.appendLine("    raise exception 'algo_params $version: stored params_hash differs from the generated one';")
        sb.appendLine("  end if;")
        sb.appendLine("  if (select count(*) from fitness.algorithm_versions where engine_version = ${q(engine)}) <> ${ModuleRegistry.entries.size} then")
        sb.appendLine("    raise exception 'algorithm_versions: expected ${ModuleRegistry.entries.size} rows for engine $engine';")
        sb.appendLine("  end if;")
        sb.appendLine("end;")
        sb.appendLine("$$;")
        out += sb.toString()
        return out
    }

    private fun literal(column: String, v: JsonElement): String = when {
        v is JsonNull -> "null"
        column in JSONB -> q(Jcs.canonicalize(v)) + "::jsonb"
        column in TEXT_ARRAYS -> {
            val items = (v as JsonArray).map { q(it.jsonPrimitive.content) }
            if (items.isEmpty()) "'{}'::text[]" else "array[" + items.joinToString(", ") + "]::text[]"
        }
        v is JsonPrimitive && v.isString -> q(v.content)
        v is JsonPrimitive -> v.content // booleans and integers
        else -> throw IllegalArgumentException("unsupported value for column $column")
    }

    private fun q(s: String): String = "'" + s.replace("'", "''") + "'"
}
